"""Download-free Create Mode fixture: a tiny random base plus synthetic evidence.

Used by tests, the CPU smoke profile and installation checks. The base is an untrained
decoder of a supported family with a byte-level BPE tokenizer (no merges), so any text
round-trips. The evidence is generated by a small scripted "agent" and a templated
writer: no private or copyrighted text.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from ..io import atomic_write_text, write_json

CHAT_TEMPLATE = (
    "{% for message in messages %}<|im_start|>{{ message['role'] }}\n{{ message['content'] }}"
    "<|im_end|>\n{% endfor %}{% if add_generation_prompt %}<|im_start|>assistant\n{% endif %}"
)


def _tokenizer(chat):
    from tokenizers import Tokenizer, decoders, models, pre_tokenizers
    from transformers import PreTrainedTokenizerFast

    alphabet = pre_tokenizers.ByteLevel.alphabet()
    specials = ["<|endoftext|>", "<|im_start|>", "<|im_end|>"]
    vocab = {token: index for index, token in enumerate(specials + sorted(alphabet))}
    backend = Tokenizer(models.BPE(vocab=vocab, merges=[]))
    backend.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    backend.decoder = decoders.ByteLevel()
    tokenizer = PreTrainedTokenizerFast(
        tokenizer_object=backend,
        bos_token="<|endoftext|>",
        eos_token="<|im_end|>" if chat else "<|endoftext|>",
        pad_token="<|endoftext|>",
        additional_special_tokens=["<|im_start|>", "<|im_end|>"],
    )
    if chat:
        tokenizer.chat_template = CHAT_TEMPLATE
    return tokenizer


def make_base(path, *, model_type="llama", layers=2, hidden=32, chat=True, tie=True, seed=0):
    import torch
    import transformers

    tokenizer = _tokenizer(chat)
    common = dict(
        vocab_size=len(tokenizer),
        hidden_size=hidden,
        intermediate_size=hidden * 2,
        num_hidden_layers=layers,
        num_attention_heads=4,
        num_key_value_heads=2,
        max_position_embeddings=512,
        tie_word_embeddings=tie,
        bos_token_id=tokenizer.bos_token_id,
        eos_token_id=tokenizer.eos_token_id,
        pad_token_id=tokenizer.pad_token_id,
    )
    classes = {
        "llama": ("LlamaConfig", "LlamaForCausalLM"),
        "qwen2": ("Qwen2Config", "Qwen2ForCausalLM"),
        "mistral": ("MistralConfig", "MistralForCausalLM"),
        "qwen3": ("Qwen3Config", "Qwen3ForCausalLM"),
    }
    config_name, model_name = classes[model_type]
    config = getattr(transformers, config_name)(**common)
    torch.manual_seed(seed)
    model = getattr(transformers, model_name)(config)
    path = Path(path)
    model.save_pretrained(path, safe_serialization=True)
    tokenizer.save_pretrained(path)
    return path


TOOLS = {
    "add": lambda a, b: a + b,
    "multiply": lambda a, b: a * b,
}


def agent_transcripts(count, seed=0):
    """A scripted source agent: visible reasoning, a tool call, a tool result, an answer."""
    rng = random.Random(seed)
    records = []
    for index in range(count):
        a, b = rng.randint(2, 40), rng.randint(2, 40)
        tool = rng.choice(sorted(TOOLS))
        word = "sum" if tool == "add" else "product"
        result = TOOLS[tool](a, b)
        call_id = f"call-{index}"
        records.append(
            {
                "id": f"agent-{index:04d}",
                "kind": "exchange",
                "conversation_id": f"conv-{index:04d}",
                "messages": [
                    {"role": "user", "content": f"What is the {word} of {a} and {b}?"},
                    {
                        "role": "assistant",
                        "reasoning": f"The user wants the {word}. I will call {tool}.",
                        "tool_calls": [
                            {"id": call_id, "name": tool, "arguments": {"a": a, "b": b}}
                        ],
                    },
                    {
                        "role": "tool",
                        "tool_call_id": call_id,
                        "content": json.dumps({"result": result}),
                    },
                    {"role": "assistant", "content": f"The {word} is {result}."},
                ],
                "decoding": {"declared_by": "fixture", "kind": "scripted"},
            }
        )
    return records


SUBJECTS = [
    "the river",
    "the committee",
    "the experiment",
    "the garden",
    "the archive",
    "the bridge",
    "the orchestra",
    "the harbour",
    "the laboratory",
    "the village",
]
VERBS = ["examined", "recorded", "described", "considered", "measured", "observed"]
OBJECTS = [
    "its history",
    "the evidence",
    "a careful account",
    "the results",
    "several hypotheses",
    "the long winter",
]


def corpus_text(paragraphs, seed=0):
    """A formal templated prose document (synthetic, public)."""
    rng = random.Random(seed)
    out = []
    for p in range(paragraphs):
        sentences = []
        for _ in range(rng.randint(3, 5)):
            sentences.append(
                f"{rng.choice(['Moreover', 'However', 'Accordingly', 'Thus'])}, "
                f"{rng.choice(SUBJECTS)} {rng.choice(VERBS)} {rng.choice(OBJECTS)}; "
                f"it is, perhaps, {rng.choice(['notable', 'evident', 'remarkable'])} that "
                f"{rng.choice(SUBJECTS)} {rng.choice(VERBS)} {rng.choice(OBJECTS)}."
            )
        if p % 6 == 0:
            out.append(f"Chapter {p // 6 + 1}")
        out.append(" ".join(sentences))
    return "\n\n".join(out) + "\n"


def make_fixture(output, *, model_type="llama", seed=0, agent=48, paragraphs=60):
    output = Path(output)
    if output.exists() and any(output.iterdir()):
        raise ValueError(f"{output} must be new or empty")
    output.mkdir(parents=True, exist_ok=True)
    base = make_base(output / "base", model_type=model_type, seed=seed)
    traces = agent_transcripts(agent, seed)
    atomic_write_text(
        output / "traces.jsonl", "".join(json.dumps(r, sort_keys=True) + "\n" for r in traces)
    )
    atomic_write_text(output / "corpus.txt", corpus_text(paragraphs, seed))
    info = {
        "base": str(base),
        "model_type": model_type,
        "traces": str(output / "traces.jsonl"),
        "corpus": str(output / "corpus.txt"),
        "note": "untrained random base and synthetic evidence for pipeline checks only",
    }
    write_json(output / "fixture.json", info)
    return info


def _command(args):
    return make_fixture(args.output, model_type=args.model_type, seed=args.seed)


def add_subcommands(commands):
    parser = commands.add_parser(
        "create-fixture",
        help="write a download-free tiny base and synthetic evidence for Create Mode checks",
    )
    parser.add_argument("--output", required=True)
    parser.add_argument(
        "--model-type", choices=["llama", "qwen2", "mistral", "qwen3"], default="llama"
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.set_defaults(func=_command)
